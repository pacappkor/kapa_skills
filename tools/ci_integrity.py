"""Reject symlinks and verify generated blobs without trusting ignore rules."""
from pathlib import Path
import subprocess
import sys


def git(*args):
    return subprocess.check_output(['git', *args])


def main():
    entries = git('ls-files', '--stage', '-z').split(b'\0')
    if any(entry.startswith(b'120000 ') for entry in entries):
        raise SystemExit('CI does not allow tracked symlinks')
    if sys.argv[1:] == ['--symlinks-only']:
        return
    for name in sys.argv[1:]:
        entry = git('ls-tree', 'HEAD', '--', name)
        if not entry.startswith((b'100644 blob ', b'100755 blob ')):
            raise SystemExit(f'{name}: HEAD must contain a regular tracked file')
        path = Path(name)
        if path.is_symlink() or not path.is_file():
            raise SystemExit(f'{name}: generated file must be regular')
        if path.read_bytes() != git('cat-file', 'blob', f'HEAD:{name}'):
            raise SystemExit(f'{name}: generated bytes differ from HEAD')
    status = git('status', '--porcelain', '--untracked-files=all', '--ignored')
    if status:
        print(status.decode('utf-8', errors='replace'))
        raise SystemExit('CI changed the working tree (including ignored files)')


if __name__ == '__main__':
    main()
